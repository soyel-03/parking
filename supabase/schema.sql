CREATE TABLE IF NOT EXISTS public.parking_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_type VARCHAR(16) NOT NULL CHECK (vehicle_type IN ('CAR', 'BIKE')),
  brand VARCHAR(100) NOT NULL,
  model VARCHAR(100) NOT NULL,
  number_plate VARCHAR(20) NOT NULL,
  slot_number VARCHAR(10) NOT NULL,
  entry_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  exit_time TIMESTAMPTZ,
  duration_minutes BIGINT NOT NULL DEFAULT 0,
  amount NUMERIC(10, 2),
  status VARCHAR(16) NOT NULL DEFAULT 'PARKED' CHECK (status IN ('PARKED', 'PAID'))
);

CREATE INDEX IF NOT EXISTS idx_parking_records_status
  ON public.parking_records (status);

CREATE UNIQUE INDEX IF NOT EXISTS uq_parking_active_plate
  ON public.parking_records (UPPER(number_plate))
  WHERE status = 'PARKED';

CREATE UNIQUE INDEX IF NOT EXISTS uq_parking_active_slot
  ON public.parking_records (slot_number)
  WHERE status = 'PARKED';

CREATE TABLE IF NOT EXISTS public.parking_settings (
  id BIGINT PRIMARY KEY,
  car_rate_per_hour NUMERIC(10, 2) NOT NULL DEFAULT 30.00,
  bike_rate_per_hour NUMERIC(10, 2) NOT NULL DEFAULT 15.00,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.parking_settings (id, car_rate_per_hour, bike_rate_per_hour)
VALUES (1, 30.00, 15.00)
ON CONFLICT (id) DO NOTHING;

-- Enable Row Level Security (server uses SUPABASE_SECRET_KEY which bypasses RLS,
-- while direct browser requests with the publishable key remain locked down).
ALTER TABLE public.parking_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parking_settings ENABLE ROW LEVEL SECURITY;
